-- 초기 스키마. 근거: docs/overnight/figma-spec.md, 도메인 경계: docs/overnight/DECISIONS.md D4~D6
-- 도메인 사이 참조는 FK 없이 BIGINT ID + 인덱스, 같은 도메인 내부만 FK를 둔다.

CREATE EXTENSION IF NOT EXISTS postgis;

-- user 도메인 -------------------------------------------------------------

CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_subject VARCHAR(255) NOT NULL,
    push_token   VARCHAR(512),
    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_users_auth_subject UNIQUE (auth_subject)
);

-- place 도메인 ------------------------------------------------------------

CREATE TABLE saved_places (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                NOT NULL,
    name       VARCHAR(50)           NOT NULL,
    location   geometry(Point, 4326) NOT NULL,
    created_at TIMESTAMPTZ           NOT NULL,
    updated_at TIMESTAMPTZ           NOT NULL,
    CONSTRAINT uk_saved_places_user_name UNIQUE (user_id, name)
);

-- parkinglot 도메인 -------------------------------------------------------

CREATE TABLE parking_lots (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100)          NOT NULL,
    location         geometry(Point, 4326) NOT NULL,
    indoor           BOOLEAN               NOT NULL,
    entrance_guide   VARCHAR(255),
    free_minutes     INTEGER               NOT NULL DEFAULT 0,
    fee_unit_minutes INTEGER,
    fee_unit_price   INTEGER,
    total_spaces     INTEGER,
    created_at       TIMESTAMPTZ           NOT NULL,
    updated_at       TIMESTAMPTZ           NOT NULL,
    CONSTRAINT ck_parking_lots_free_minutes CHECK (free_minutes >= 0),
    CONSTRAINT ck_parking_lots_fee CHECK (
        (fee_unit_minutes IS NULL AND fee_unit_price IS NULL)
        OR (fee_unit_minutes > 0 AND fee_unit_price >= 0)
    ),
    CONSTRAINT ck_parking_lots_total_spaces CHECK (total_spaces IS NULL OR total_spaces > 0)
);

CREATE INDEX idx_parking_lots_location ON parking_lots USING GIST (location);

CREATE TABLE parking_lot_occupancy_forecasts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parking_lot_id BIGINT      NOT NULL REFERENCES parking_lots (id),
    target_at      TIMESTAMPTZ NOT NULL,
    occupancy_rate SMALLINT    NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_occupancy_forecasts_lot_target UNIQUE (parking_lot_id, target_at),
    CONSTRAINT ck_occupancy_forecasts_rate CHECK (occupancy_rate BETWEEN 0 AND 100)
);

-- arrival 도메인 ----------------------------------------------------------

CREATE TABLE arrival_sessions (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                    BIGINT                NOT NULL,
    destination_name           VARCHAR(100)          NOT NULL,
    destination_location       geometry(Point, 4326) NOT NULL,
    destination_parking_lot_id BIGINT,
    waypoint_parking_lot_id    BIGINT,
    expected_arrival_at        TIMESTAMPTZ           NOT NULL,
    status                     VARCHAR(20)           NOT NULL,
    ended_at                   TIMESTAMPTZ,
    created_at                 TIMESTAMPTZ           NOT NULL,
    updated_at                 TIMESTAMPTZ           NOT NULL,
    CONSTRAINT ck_arrival_sessions_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_arrival_sessions_ended CHECK ((status = 'ACTIVE') = (ended_at IS NULL))
);

CREATE INDEX idx_arrival_sessions_user_id ON arrival_sessions (user_id);
CREATE UNIQUE INDEX uk_arrival_sessions_user_active ON arrival_sessions (user_id) WHERE status = 'ACTIVE';
CREATE INDEX idx_arrival_sessions_destination_lot ON arrival_sessions (destination_parking_lot_id);
CREATE INDEX idx_arrival_sessions_waypoint_lot ON arrival_sessions (waypoint_parking_lot_id);

-- parking 도메인 ----------------------------------------------------------

CREATE TABLE parking_records (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT                NOT NULL,
    parking_lot_id   BIGINT,
    location         geometry(Point, 4326) NOT NULL,
    parked_at        TIMESTAMPTZ           NOT NULL,
    spot_memo        VARCHAR(100),
    sent_to_phone_at TIMESTAMPTZ,
    exited_at        TIMESTAMPTZ,
    created_at       TIMESTAMPTZ           NOT NULL,
    updated_at       TIMESTAMPTZ           NOT NULL,
    CONSTRAINT ck_parking_records_exited CHECK (exited_at IS NULL OR exited_at >= parked_at)
);

CREATE INDEX idx_parking_records_user_parked_at ON parking_records (user_id, parked_at DESC);
CREATE UNIQUE INDEX uk_parking_records_user_active ON parking_records (user_id) WHERE exited_at IS NULL;
CREATE INDEX idx_parking_records_parking_lot ON parking_records (parking_lot_id);
